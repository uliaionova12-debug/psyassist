import type { ClientMap, RazborFormat } from "@/lib/razbor/config";
import { RISK_CLIENT_TEXT } from "@/lib/razbor/risk";

export function fallbackClientMap(
  format: RazborFormat,
  risk: boolean,
): ClientMap {
  const couple = format === "couple";
  const short = couple
    ? "Спасибо, что рассказали о том, что происходит в вашей паре. Уже то, что вы ищете способ разобраться вместе, — важный шаг. Подробную карту ситуации сейчас подготовить не получилось, но ваши ответы сохранены, и Юлия прочитает их перед встречей."
    : "Спасибо, что поделились тем, что происходит. Уже то, что вы решили в этом разобраться, — важный шаг. Подробную карту ситуации сейчас подготовить не получилось, но ваши ответы сохранены, и Юлия прочитает их перед встречей.";
  return {
    short: risk ? `${short} ${RISK_CLIENT_TEXT}` : short,
    focus: couple
      ? [
          "Что именно сейчас происходит между вами",
          "Чего каждый из вас хочет от отношений",
          "Что уже пробовали и что мешает договориться",
        ]
      : [
          "Что именно вас сейчас беспокоит",
          "Как это влияет на вашу жизнь",
          "Чего вы хотите добиться",
        ],
    first_session: couple
      ? "На первой встрече вы вдвоём спокойно расскажете о ситуации, каждый со своей стороны. Юлия поможет услышать друг друга и вместе определить, с чего начать."
      : "На первой встрече вы спокойно расскажете о ситуации, а Юлия поможет разобраться, что происходит, и вместе с вами определит, с чего начать.",
    next_step:
      "Выберите удобное время для консультации — встреча проходит онлайн и длится 50 минут.",
  };
}
