const RISK_PATTERNS = [
  /суицид/i,
  /покончить\s+с\s+собой/i,
  /не\s+хочу\s+жить/i,
  /не\s+хочется\s+жить/i,
  /убить\s+себя/i,
  /уйти\s+из\s+жизни/i,
  /свести\s+сч[её]ты/i,
  /причинить\s+себе\s+вред/i,
  /самоповрежд/i,
  /порезать\s+себя/i,
  /жить\s+незачем/i,
];

export function hasRiskSignals(text: string): boolean {
  return RISK_PATTERNS.some((re) => re.test(text));
}

